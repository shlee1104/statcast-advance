"""The hitting plan: tendency tables turned into sentences a hitter can use.

Everything else in this project measures. This module writes the part of an
advance report a player actually reads before he walks to the plate: a few
short lines, split by which side of the plate he hits from, saying what to look
for and what to lay off.

The people who build these reports describe the job the same way. One front
office described taking "a phone book's amount of information" and paring it
to a few pages plus one-sentence notes for in-game use; another warned that the
staff's job is to separate what is usable from what is cosmetic. So the rules
here are deliberately few, each one gated on sample size, and each sentence
carries the number of pitches behind it.

Two constraints shape the wording.

The plan is built from how OFTEN he does things, not from what they cost him in
runs. Run-value estimates do not resolve at one season of one pitcher (see
`flags.benjamini_hochberg`), while usage rates on several hundred pitches do.
A plan built on frequency is what advance scouting has always been; claiming
the run cost would be claiming precision the data does not have.

It is written from the HITTER's point of view, because the hitter is the
reader. A count where the pitcher is behind is "when you're ahead in the
count", and the tendency tables are flipped accordingly here, not in the
reader's head.

Nothing here is generated by a language model. Every sentence comes from a
rule with a threshold, so the same data always produces the same plan and any
line can be traced to the rows that produced it.
"""

from __future__ import annotations

import pandas as pd

from src import config
from src.metrics import counts, location, splits

# What hitters and coaches call each pitch. "Four-seam" rather than "fastball"
# for FF, because a pitcher with a sinker has two fastballs and "sit fastball"
# would not say which.
COACH_NAMES: dict[str, str] = {
    "FF": "four-seam",
    "SI": "sinker",
    "FC": "cutter",
    "FS": "splitter",
    "CH": "changeup",
    "SC": "screwball",
    "FO": "forkball",
    "CU": "curveball",
    "KC": "knuckle-curve",
    "SL": "slider",
    "ST": "sweeper",
    "SV": "slurve",
    "KN": "knuckleball",
}

# Hard, breaking, offspeed — the three buckets a hitter actually sits on. "Sit
# hard" is a plan; "sit four-seam 34%, sinker 19%, cutter 18%" is a table.
PITCH_FAMILY: dict[str, str] = {
    "FF": "hard", "SI": "hard", "FC": "hard",
    "CU": "breaking", "KC": "breaking", "SL": "breaking",
    "ST": "breaking", "SV": "breaking",
    "FS": "offspeed", "CH": "offspeed", "SC": "offspeed", "FO": "offspeed",
}

SIDE_NAMES: dict[str, str] = {"L": "lefties", "R": "righties"}


def name(pitch_type: str) -> str:
    """A pitch code as a coach would say it."""
    return COACH_NAMES.get(pitch_type, pitch_type.lower())


def _pct(value: float) -> str:
    return f"{value:.0%}"


def _key(label: str, text: str, n: int) -> dict:
    return {"label": label, "text": text, "n": int(n)}


def _top(usage: pd.DataFrame, situation: str, side: str) -> pd.DataFrame:
    rows = usage[(usage["situation"] == situation) & (usage["stand"] == side)]
    return rows.sort_values("share", ascending=False)


def _list_pitches(rows: pd.DataFrame, limit: int = 3) -> str:
    return ", ".join(
        f"{name(r.pitch_type)} {_pct(r.share)}" for r in rows.head(limit).itertuples()
    )


# ---------------------------------------------------------------------------
# Per-side keys
# ---------------------------------------------------------------------------


def _cut(key: str, default: float) -> float:
    """A plan cutoff from config.yaml's `plan` section.

    Every threshold that decides which sentence a hitter reads lives in config,
    not here, so the calibration run across many pitchers can move them without
    touching the wording.
    """
    return float(config.get(f"plan.{key}", default))


# ---------------------------------------------------------------------------
# Measurements behind each per-side rule
#
# Each returns the numbers a rule reads, or None when the sample is below its
# gate. They are separate from the sentence-writing functions below so that a
# calibration run can record the numbers for every pitcher — including the
# ones where the rule stays silent, which are exactly the cases needed to see
# whether a cutoff is in the right place.
# ---------------------------------------------------------------------------


def first_pitch_numbers(frame: pd.DataFrame, usage: pd.DataFrame, side: str) -> dict | None:
    """First-pitch mix to this side, and how often TAKEN first pitches are strikes."""
    min_n = int(config.get("flags.min_n.first_pitch", 30))
    rows = _top(usage, "first_pitch", side)
    if len(rows) == 0 or int(rows.iloc[0]["situation_n"]) < min_n:
        return None

    side_frame = frame[(frame["stand"] == side)
                       & (frame["balls"] == 0) & (frame["strikes"] == 0)]
    taken = side_frame[~side_frame["is_swing"].eq(True)]
    called = (
        float(taken["is_called_strike"].eq(True).mean())
        if len(taken) >= min_n else float("nan")
    )
    lead = rows.iloc[0]
    second = rows.iloc[1] if len(rows) > 1 else None
    return {
        "n": int(lead["situation_n"]),
        "top": lead.pitch_type,
        "top_share": float(lead.share),
        "second": second.pitch_type if second is not None else None,
        "second_share": float(second.share) if second is not None else float("nan"),
        "takes": int(len(taken)),
        "called_on_takes": called,
    }


def hitters_count_numbers(usage: pd.DataFrame, side: str) -> dict | None:
    """The mix when the hitter is ahead: hard-family share and the top pitch."""
    min_n = int(config.get("flags.min_n.predictable_count", 20)) + 10
    rows = _top(usage, "pitcher_behind", side)
    if len(rows) == 0 or int(rows.iloc[0]["situation_n"]) < min_n:
        return None

    families = rows.assign(
        family=rows["pitch_type"].map(PITCH_FAMILY).fillna("other")
    ).groupby("family")["share"].sum()
    lead = rows.iloc[0]
    return {
        "n": int(lead["situation_n"]),
        "hard_share": float(families.get("hard", 0.0)),
        "top": lead.pitch_type,
        "top_share": float(lead.share),
        "rows": rows,
    }


def two_strike_numbers(frame: pd.DataFrame, usage: pd.DataFrame, side: str) -> dict | None:
    """His two-strike pitch to this side, its miss rate, and how often it ends low."""
    min_n = int(config.get("flags.min_n.first_pitch", 30))
    rows = _top(usage, "two_strikes", side)
    if len(rows) == 0 or int(rows.iloc[0]["situation_n"]) < min_n:
        return None

    lead = rows.iloc[0]
    pitches = frame[(frame["stand"] == side) & (frame["strikes"] == 2)
                    & (frame["pitch_type"] == lead.pitch_type)]
    swings = int(pitches["is_swing"].eq(True).sum())
    whiffs = int(pitches["is_whiff"].eq(True).sum())
    located = pitches.dropna(subset=["plate_z", "sz_bot"])
    return {
        "n": int(lead["situation_n"]),
        "top": lead.pitch_type,
        "top_share": float(lead.share),
        "swings": swings,
        "whiff": whiffs / swings if swings else float("nan"),
        "below": (
            float((located["plate_z"] < located["sz_bot"]).mean())
            if len(located) else float("nan")
        ),
    }


def rare_pitches(frame: pd.DataFrame, side: str, max_share: float | None = None) -> dict | None:
    """Arsenal pitches this side sees less than `max_share` of the time."""
    if max_share is None:
        max_share = _cut("rare_share", 0.03)
    working = counts.restrict_to_arsenal(frame)
    side_frame = working[working["stand"] == side]
    if len(side_frame) < 100:
        return None

    shares = side_frame["pitch_type"].value_counts(normalize=True)
    arsenal = list(working["pitch_type"].value_counts().index)
    return {
        "n": int(len(side_frame)),
        "arsenal_size": len(arsenal),
        "rare": [(p, float(shares.get(p, 0.0))) for p in arsenal
                 if shares.get(p, 0.0) < max_share],
        # How close this side comes to the cutoff, recorded even when nothing
        # is rare, so a calibration run can see where the line sits.
        "min_share": min(float(shares.get(p, 0.0)) for p in arsenal),
    }


