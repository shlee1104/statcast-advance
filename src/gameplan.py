def recent_change_key(frame: pd.DataFrame, last_n: int = 5) -> dict | None:
    """What has changed in his most recent outings.

    Only shifts the recent-form test marks notable are mentioned, and a
    velocity change only if it is at least half a mile per hour, so this line
    stays empty for a pitcher who is simply doing what he always does.
    """
    form = splits.recent_form(frame, last_n=last_n)
    if not form["last_n"] or form["shifts"].empty:
        return None

    notable = form["shifts"][form["shifts"]["notable"]]
    parts = []
    for r in notable.itertuples():
        direction = "up" if r.delta > 0 else "down"
        parts.append(f"{name(r.pitch_type)} {direction} to {_pct(r.recent_share)} "
                     f"from {_pct(r.earlier_share)}")

    velo = form["velo_delta"]
    if velo == velo and abs(velo) >= 0.5 and form["fastball"]:
        direction = "up" if velo > 0 else "down"
        parts.append(f"{name(form['fastball'])} velocity {direction} "
                     f"{abs(velo):.1f} mph")

    if not parts:
        return None

    def short(date: str) -> str:
        stamp = pd.Timestamp(date)
        return f"{stamp.strftime('%b')} {stamp.day}"

    first, last = short(form["dates"][-1]), short(form["dates"][0])
    window = f"Last {form['last_n']} outings ({first} to {last}"

    # Postseason outings are a different setting — shorter rest, more relief,
    # more adrenaline — and a reader should know when "lately" means October.
    if "game_type" in frame.columns:
        recent_types = (
            frame[frame["game_date"].astype(str).str[:10].isin(form["dates"])]
            .drop_duplicates("game_pk")["game_type"]
        )
        post = int((recent_types != "R").sum())
        if post == len(recent_types) and post:
            window += ", all postseason"
        elif post:
            window += f", {post} postseason"
    window += ")"

    text = window + ": " + "; ".join(parts) + "."
    return _key("Lately", text, form["n_recent"])


def count_tell_key(frame: pd.DataFrame, min_lift: float | None = None) -> dict | None:
    """A pitch that jumps in specific counts to more than double his norm.

    3-0 is excluded. Nearly every pitcher throws a fastball 3-0, so a lift there
    describes the count, not the pitcher, and a coach already knows it.
    """
    if min_lift is None:
        min_lift = _cut("count_tell_lift", 2.0)
    min_n = int(config.get("flags.min_n.predictable_count", 20))
    lifts = counts.count_lifts(frame, min_n=min_n)
    if len(lifts) == 0:
        return None

    strong = lifts[(lifts["lift"] >= min_lift) & (lifts["count"] != "3-0")]
    if len(strong) == 0:
        return None

    pitch = strong.sort_values("score", ascending=False).iloc[0]["pitch_type"]
    rows = strong[strong["pitch_type"] == pitch].sort_values("count")
    which = " and ".join(rows["count"])
    peak = rows["share"].max()
    own = rows.iloc[0]["own_rate"]
    n = int(rows["n"].sum())

    text = (f"In {which} the {name(pitch)} jumps to about {_pct(peak)} — more "
            f"than double his normal {_pct(own)}. Expect it there.")
    return _key("Count tell", text, n)


def location_key(frame: pd.DataFrame) -> dict | None:
    """Where the ball is headed says which pitch it is, when that holds strongly."""
    min_n = int(config.get("flags.min_n.location_tell", 40))
    min_lift = float(config.get("flags.thresholds.location_tell_lift", 1.35))
    min_share = float(config.get("flags.thresholds.location_tell_share", 0.45))

    tells = location.location_tells(frame, by="v_band", min_n=min_n)
    if len(tells) == 0:
        return None
    strong = tells[(tells["lift"] >= min_lift) & (tells["p_pitch"] >= min_share)]
    if len(strong) == 0:
        return None

    top = strong.sort_values("score", ascending=False).iloc[0]
    # DOWN is the bottom third of his zone AND everything below it, so "down"
    # rather than "down in the zone".
    where = {"UP": "up in the zone", "DOWN": "down",
             "MIDDLE": "at the belt"}.get(top.band, top.band.lower())
    text = (f"If it's {where}, it's probably the {name(top.pitch_type)} "
            f"({_pct(top.p_pitch)} of pitches there).")
    return _key("Read the height", text, int(top.n))


def count_headline(frame: pd.DataFrame, min_lift: float = 1.25) -> str | None:
    """One sentence stating what the count grid shows, for its title.

    A chart title should state the finding, not name the metric. This finds the
    pitch that rises most in hitter's counts and the one that rises most with
    two strikes, and says so — adding that they stay out of each other's counts
    when that is also true. Returns None when neither rises enough to be worth
    a headline, and the chart gets a plain title instead.
    """
    regions = counts.count_region_lifts(frame)
    if len(regions) == 0:
        return None

    # A pitcher with no pitches in one region has no lift there. That must
    # leave the headline out, not raise — an earlier version crashed the whole
    # report on a pitcher who had never thrown a two-strike pitch in the
    # sample, which a short-season pitcher can genuinely produce.
    h_lifts = regions["hitter_lift"].dropna()
    t_lifts = regions["two_strike_lift"].dropna()
    if h_lifts.empty and t_lifts.empty:
        return None

    hitter = h_lifts.idxmax() if len(h_lifts) else None
    two = t_lifts.idxmax() if len(t_lifts) else None
    h_lift = float(h_lifts.max()) if len(h_lifts) else 0.0
    t_lift = float(t_lifts.max()) if len(t_lifts) else 0.0

    if h_lift < min_lift and t_lift < min_lift:
        return None
    if hitter is not None and hitter == two:
        return (f"The {name(hitter)} rises both in hitter's counts and with "
                f"two strikes.")

    parts = []
    if h_lift >= min_lift:
        parts.append(f"the {name(hitter)} comes out in hitter's counts")
    if t_lift >= min_lift:
        parts.append(f"the {name(two)} with two strikes")
    sentence = " and ".join(parts)
    sentence = sentence[0].upper() + sentence[1:]

    apart = (
        h_lift >= min_lift and t_lift >= min_lift
        and float(regions.loc[hitter, "two_strike_lift"]) < 0.8
        and float(regions.loc[two, "hitter_lift"]) < 0.8
    )
    if apart:
        sentence += ", and each rarely shows up in the other's counts"
    return sentence + "."


def platoon_headline(frame: pd.DataFrame, rare: float = 0.03) -> str | None:
    """One sentence stating what the platoon slope chart shows.

    Two kinds of split get named. A pitch one side almost never sees is the
    sharpest — it shrinks that side's problem — and a large usage gap on a pitch
    both sides do see. When the largest gap is big (15 points or more) it leads,
    because it changes the plan for every at-bat on one side; otherwise the
    never-see list leads and the biggest remaining gap follows.
    """
    usage = counts.restrict_to_arsenal(frame)
    if len(usage) == 0:
        return None

    shares = {
        side: usage[usage["stand"] == side]["pitch_type"].value_counts(normalize=True)
        for side in ("L", "R")
    }
    if any(len(s) == 0 for s in shares.values()):
        return None
    pitches = list(usage["pitch_type"].value_counts().index)

    def share(side: str, p: str) -> float:
        return float(shares[side].get(p, 0.0))

    unseen = {
        side: [p for p in pitches
               if share(side, p) < rare and share("R" if side == "L" else "L", p) >= rare]
        for side in ("L", "R")
    }
    gaps = sorted(
        ((p, share("L", p) - share("R", p)) for p in pitches
         if p not in unseen["L"] + unseen["R"]),
        key=lambda pair: -abs(pair[1]),
    )

    def gap_clause(p: str, g: float) -> str:
        more, less = ("lefties", "righties") if g > 0 else ("righties", "lefties")
        hi = share("L" if g > 0 else "R", p)
        lo = share("R" if g > 0 else "L", p)
        return f"{more} get the {name(p)} {_pct(hi)} of the time and {less} {_pct(lo)}"

    unseen_clauses = [
        f"{SIDE_NAMES[side]} almost never see the {' or the '.join(name(p) for p in ps)}"
        for side, ps in unseen.items() if ps
    ]

    if gaps and abs(gaps[0][1]) >= 0.15:
        text = gap_clause(*gaps[0])
        if unseen_clauses:
            text += ", and " + " and ".join(unseen_clauses)
    elif unseen_clauses:
        text = " and ".join(unseen_clauses)
        if gaps and abs(gaps[0][1]) >= 0.08:
            p, g = gaps[0]
            more = "L" if g > 0 else "R"
            if len([s for s in unseen if unseen[s]]) == 1 and unseen[more]:
                # Same side as the never-see clause: continue the sentence
                # rather than naming the side again.
                other = "R" if more == "L" else "L"
                text += (f", and get the {name(p)} more often "
                         f"({_pct(share(more, p))} to {_pct(share(other, p))} "
                         f"for {SIDE_NAMES[other]})")
            else:
                text += "; " + gap_clause(p, g)
    elif gaps and abs(gaps[0][1]) >= 0.08:
        text = gap_clause(*gaps[0])
    else:
        return "His mix barely changes with the hitter's side."

    return text[0].upper() + text[1:] + "."


def movement_headline(frame: pd.DataFrame, min_usage: float = 0.05) -> str | None:
    """One sentence on how his best swing-and-miss pitch moves against his fastball.

    Separation is what makes a secondary pitch hard to hit: the same arm speed
    with very different movement. So the headline compares his best whiff pitch
    (by whiffs per swing, among non-fastballs he uses at least `min_usage`) with
    his primary fastball — how much more it drops, how much more it runs, and
    how much slower it is. "Only N mph slower" is said only when the gap is
    small enough to be a reason the pitch works.

    It says nothing about whether the two look alike out of the hand. That is a
    tunneling claim, and nothing in this project measures it yet.
    """
    from src.metrics import arsenal

    table = arsenal.scout_arsenal(frame)
    profile = arsenal.profile(frame)
    fastball = splits.primary_fastball(counts.restrict_to_arsenal(frame))
    if len(table) == 0 or fastball not in table.index:
        return None

    candidates = table[
        (table["usage"] >= min_usage)
        & (~table.index.map(lambda p: PITCH_FAMILY.get(p) == "hard"))
    ].dropna(subset=["whiff_rate"])
    if len(candidates) == 0:
        return None

    best = candidates["whiff_rate"].idxmax()
    drop = float(table.loc[fastball, "ivb"] - table.loc[best, "ivb"])
    run = float(table.loc[best, "arm_run"] - table.loc[fastball, "arm_run"])
    slower = float(profile.loc[fastball, "velo"] - profile.loc[best, "velo"])

    moves = []
    if abs(drop) >= 4:
        moves.append(f"drops {abs(drop):.0f} inches {'more' if drop > 0 else 'less'}")
    if abs(run) >= 6:
        side = "his arm side" if run > 0 else "his glove side"
        moves.append(f"moves {abs(run):.0f} inches more to {side}")
    if not moves:
        return (f"The {name(best)} is his best swing-and-miss pitch "
                f"({_pct(table.loc[best, 'whiff_rate'])} of swings miss).")

    speed = (f" at only {slower:.0f} mph slower" if 0 < slower <= 6
             else f", {slower:.0f} mph slower")
    return (f"The {name(best)} is his best swing-and-miss pitch "
            f"({_pct(table.loc[best, 'whiff_rate'])} of swings miss): it "
            f"{' and '.join(moves)} than his {name(fastball)}{speed}.")


